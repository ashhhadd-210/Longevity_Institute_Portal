    <p>
        A collaborator profile is a selected representation of your professional work,
        written for other collaborators of the Institute. It is not a complete CV, and nobody is
        expected to include everything.
    </p>
    <p>
        <strong>Accuracy.</strong> Everything on your profile should be true and current as
        you describe it. Describe roles, programs and affiliations as they actually were,
        and never in a way that implies a degree, appointment or status you did not hold.
    </p>
    <p>
        <strong>Professional presentation.</strong> Write as you would for respected
        colleagues in other professions: plainly, and without promotional claims.
    </p>
    <p>
        <strong>Your photograph.</strong> An individual professional image of you, ideally
        head and shoulders. No logos, avatars, group photographs or organizational graphics.
        Cultural and religious dress is entirely welcome.
    </p>
    <p>
        <strong>Credentials.</strong> Show only credentials you have earned and are entitled
        to use.
    </p>
    <p>
        The Institute may ask you to adjust anything that falls outside these standards. It
        will always ask, rather than change your profile for you.
    </p>
